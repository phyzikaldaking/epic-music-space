#!/usr/bin/env node

import { execSync } from 'node:child_process';

const title = process.env.GUARDIAN_PR_TITLE || 'Guardian repair: automated platform protection update';
const body = process.env.GUARDIAN_PR_BODY || `## EMS Guardian Repair PR\n\nThis PR was generated by EMS Guardian automation.\n\n### Required verification\n\n- npm run lint\n- npm run typecheck\n- npm run build\n- node scripts/guardian/route-smoke.mjs\n- node scripts/guardian/freeze-watch.mjs\n- node scripts/guardian/perf-budget.mjs\n- node scripts/guardian/security-audit.mjs\n\n### Merge rule\n\nMerge only after all required checks pass.`;

function run(command) {
  console.log(`$ ${command}`);
  return execSync(command, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }).trim();
}

const branch = run('git branch --show-current');
if (!branch || branch === 'main') {
  console.error('Refusing to open repair PR from main. Create a guardian/repair-* branch first.');
  process.exit(1);
}

run(`git push --set-upstream origin ${branch}`);
run(`gh pr create --title "${title.replace(/"/g, '\\"')}" --body "${body.replace(/"/g, '\\"')}" --base main --head ${branch}`);
console.log('EMS Guardian repair PR opened.');
